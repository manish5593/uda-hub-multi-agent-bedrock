"""Alembic migrations (service/migrations) and the seed job that runs after them.

Every test runs on a fresh SQLite file. If UDAHUB_TEST_POSTGRES_URL is set (a role that may create
databases, e.g. postgresql+psycopg://postgres:pw@localhost:5432/postgres), they also run on a fresh
Postgres database each, which is what CI does.
"""
import json
import os
import uuid

import pytest
from alembic import command
from alembic.script import ScriptDirectory
from alembic.util import AutogenerateDiffsDetected
from sqlalchemy import create_engine, func, inspect, select, text
from sqlalchemy.engine import make_url

from service.migrations.common import BASELINE, DATABASES, VERSION_TABLE, alembic_config, upgrade
from service.scripts import seed

POSTGRES_ADMIN_URL = os.getenv("UDAHUB_TEST_POSTGRES_URL")
NAMES = sorted(DATABASES)
SEEDED = sorted(name for name, db in DATABASES.items() if db.seeded)


@pytest.fixture(params=["sqlite", "postgres"])
def new_db(request, tmp_path):
    """A factory for empty databases on the parametrised backend."""
    created = []

    def make() -> str:
        if request.param == "sqlite":
            return f"sqlite:///{tmp_path / f'{uuid.uuid4().hex}.db'}"
        if not POSTGRES_ADMIN_URL:
            pytest.skip("UDAHUB_TEST_POSTGRES_URL not set")
        name = f"udahub_test_{uuid.uuid4().hex[:12]}"
        admin = create_engine(POSTGRES_ADMIN_URL, isolation_level="AUTOCOMMIT")
        with admin.connect() as conn:
            conn.execute(text(f'CREATE DATABASE "{name}"'))
        admin.dispose()
        created.append(name)
        return make_url(POSTGRES_ADMIN_URL).set(database=name).render_as_string(hide_password=False)

    yield make
    if created:
        admin = create_engine(POSTGRES_ADMIN_URL, isolation_level="AUTOCOMMIT")
        with admin.connect() as conn:
            for name in created:
                conn.execute(text(f'DROP DATABASE IF EXISTS "{name}" WITH (FORCE)'))
        admin.dispose()


def tables(url: str) -> set:
    engine = create_engine(url)
    try:
        return set(inspect(engine).get_table_names())
    finally:
        engine.dispose()


def run(name: str, url: str, action, *args):
    """Run an alembic command on one database, the way service.migrations.common.upgrade does."""
    engine = create_engine(url)
    try:
        with engine.begin() as connection:
            action(alembic_config(name, url, connection), *args)
    finally:
        engine.dispose()


@pytest.mark.parametrize("name", NAMES)
def test_each_history_has_one_head(name):
    # Two revisions with the same parent (e.g. from two branches) must be merged before deploying
    script = ScriptDirectory.from_config(alembic_config(name))
    assert script.get_heads() == [script.get_current_head()]
    assert script.get_base() == BASELINE


@pytest.mark.parametrize("name", NAMES)
def test_upgrade_creates_the_tables_of_that_database_only(new_db, name):
    url = new_db()
    assert upgrade(name, url) == ScriptDirectory.from_config(alembic_config(name)).get_current_head()
    assert tables(url) == set(DATABASES[name].tables) | {VERSION_TABLE}


@pytest.mark.parametrize("name", NAMES)
def test_migrations_match_the_models(new_db, name):
    """Fails when a model changes without a migration: run `alembic ... revision --autogenerate`."""
    url = new_db()
    upgrade(name, url)
    try:
        run(name, url, command.check)
    except AutogenerateDiffsDetected as exc:
        pytest.fail(f"{name}: the models differ from the migrations:\n{exc}")


@pytest.mark.parametrize("name", NAMES)
def test_downgrade_to_base_and_back(new_db, name):
    url = new_db()
    upgrade(name, url)
    run(name, url, command.downgrade, "base")
    assert tables(url) == {VERSION_TABLE}
    upgrade(name, url)  # e.g. the tickets enum type was dropped too, or this would fail on Postgres
    assert tables(url) == set(DATABASES[name].tables) | {VERSION_TABLE}


def test_upgrade_is_idempotent(new_db):
    url = new_db()
    assert upgrade("tickets", url) == upgrade("tickets", url)


def test_database_created_before_migrations_is_stamped_and_keeps_its_data(new_db):
    """Databases made by the old seed (create_all, no version table) are adopted, not recreated."""
    url = new_db()
    db = DATABASES["knowledge"]
    engine = create_engine(url)
    db.metadata.create_all(engine, tables=[t for t in db.metadata.sorted_tables if db.includes(t.name)])
    with engine.begin() as conn:
        conn.execute(text("INSERT INTO accounts (account_id, account_name) VALUES ('a1', 'Existing')"))
    engine.dispose()

    assert upgrade("knowledge", url) == BASELINE
    engine = create_engine(url)
    with engine.connect() as conn:
        assert conn.execute(text("SELECT account_name FROM accounts")).scalar() == "Existing"
    engine.dispose()


def test_database_with_only_some_tables_is_refused(new_db):
    url = new_db()
    engine = create_engine(url)
    DATABASES["tickets"].metadata.tables["accounts"].create(engine)
    engine.dispose()
    with pytest.raises(RuntimeError, match="schema version is unknown"):
        upgrade("tickets", url)


def test_seed_needs_the_migrations_first(new_db):
    with pytest.raises(RuntimeError, match="service.scripts.migrate"):
        seed.seed("cultpass", new_db())


@pytest.mark.parametrize("name", SEEDED)
def test_seed_loads_the_demo_data_once(new_db, name):
    url = new_db()
    upgrade(name, url)
    first = seed.seed(name, url)
    assert first and all(isinstance(n, int) for n in first.values())
    assert set(seed.seed(name, url).values()) == {"kept existing rows"}

    db = DATABASES[name]
    table = db.metadata.tables[db.tables[0]]
    engine = create_engine(url)
    with engine.connect() as conn:
        assert conn.execute(select(func.count()).select_from(table)).scalar() == first[table.name]
    engine.dispose()


def test_local_customers_survive_a_reset_with_their_login(new_db, tmp_path):
    """service/local/customers.json: your own demo customer is added after the demo data, again after
    --reset, never twice, and with a password hash their login comes back in a new auth database."""
    import bcrypt
    cultpass_url, auth_url = new_db(), new_db()
    upgrade("cultpass", cultpass_url)
    upgrade("auth", auth_url)
    me = {"user_id": "9f8e7d", "full_name": "Demo Presenter", "email": "Presenter@Example.com",
          "subscription": {"subscription_id": "6c5b4a", "tier": "premium", "monthly_quota": 4},
          "reservations": [{"reservation_id": "3e2d1c", "experience_id": "8aaed6"}],
          "password_hash": bcrypt.hashpw(b"a-good-password-1", bcrypt.gensalt(4)).decode()}
    path = tmp_path / "customers.json"
    path.write_text(json.dumps([me]))
    customers = seed.load_local_customers(path)

    engine = create_engine(cultpass_url)
    meta = DATABASES["cultpass"].metadata.tables

    def state():
        with engine.connect() as conn:
            users = conn.execute(select(func.count()).select_from(meta["users"])
                                 .where(meta["users"].c.email == "presenter@example.com")).scalar()
            slots = conn.execute(select(meta["experiences"].c.slots_available)
                                 .where(meta["experiences"].c.experience_id == "8aaed6")).scalar()
            booked = conn.execute(select(meta["reservations"].c.status)
                                  .where(meta["reservations"].c.reservation_id == "3e2d1c")).scalar()
        return users, slots, booked

    seed.seed("cultpass", cultpass_url)
    with engine.connect() as conn:
        demo_slots = conn.execute(select(meta["experiences"].c.slots_available)
                                  .where(meta["experiences"].c.experience_id == "8aaed6")).scalar()
    assert seed.add_local_customers(cultpass_url, auth_url, customers) == ["presenter@example.com"]
    assert state() == (1, demo_slots - 1, "reserved")
    assert seed.add_local_customers(cultpass_url, auth_url, customers) == []   # never twice
    assert state() == (1, demo_slots - 1, "reserved")

    seed.seed("cultpass", cultpass_url, reset=True)                           # the reset drops them...
    assert state()[0] == 0
    seed.add_local_customers(cultpass_url, auth_url, customers)               # ...and they come back
    assert state() == (1, demo_slots - 1, "reserved")
    engine.dispose()

    auth = create_engine(auth_url)
    with auth.connect() as conn:
        rows = conn.execute(text("select email, external_user_id from credentials")).all()
    auth.dispose()
    assert rows == [("presenter@example.com", "9f8e7d")]


